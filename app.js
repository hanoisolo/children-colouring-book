/**
 * DOM controller for the colouring book.
 *
 * This module is wiring only: it reads the form, hands the two strings to
 * `generateBook` or `generateImageBook`, paints the returned cards into the
 * preview grid, and turns the returned bytes into a download. Every decision
 * worth testing lives in `src/book.js` and below, so the headless suite covers
 * the real path without a DOM shim.
 *
 * Which pipeline runs is decided by one thing: whether an API key is present.
 * A key means six generated images; no key means the offline vector book. There
 * is no mode switch to get out of step with the key field.
 *
 * Importing this module in Node is safe: the wiring only runs when `document`
 * exists.
 */

import {
  costNoteText,
  drawingStatusText,
  generateBook,
  generateImageBook,
  hasApiKey,
  partialFailureText,
  readyStatusText,
  submitUiState,
  themeNoteText,
} from './src/book.js';
import { PAGE_HEIGHT, PAGE_WIDTH } from './src/page.js';

// The inline boot check in index.html reads this. A page opened over file://
// cannot fetch a module at all, so this never runs there and the notice
// explains why nothing generated.
if (typeof window !== 'undefined') {
  window.__bookBooted = true;
}

const percent = (value, total) => `${((value / total) * 100).toFixed(4)}%`;

/**
 * Build one preview card.
 *
 * A vector card is a standalone SVG. An image card is a page-shaped frame with
 * the JPEG positioned by the same `rect` the PDF uses, and the cover's overlay
 * SVG laid over the whole page. Sharing the rect is what stops the preview and
 * the print from disagreeing about where the artwork and the name sit.
 *
 * @param {object} card
 * @returns {HTMLElement}
 */
function renderCard(card) {
  const figure = document.createElement('figure');
  figure.className = 'page-preview';
  figure.setAttribute('data-role', 'page-preview');
  figure.setAttribute('data-page-index', String(card.index));

  if (card.image) {
    const frame = document.createElement('div');
    frame.className = 'page-frame';

    const img = document.createElement('img');
    img.className = 'page-image';
    img.src = `data:${card.image.mimeType};base64,${card.image.base64}`;
    img.alt = card.label;
    img.decoding = 'async';
    const rect = card.image.rect;
    img.style.left = percent(rect.x, PAGE_WIDTH);
    img.style.top = percent(rect.y, PAGE_HEIGHT);
    img.style.width = percent(rect.w, PAGE_WIDTH);
    img.style.height = percent(rect.h, PAGE_HEIGHT);
    frame.append(img);

    if (card.overlaySvg) {
      const overlay = document.createElement('div');
      overlay.className = 'page-overlay';
      overlay.innerHTML = card.overlaySvg;
      frame.append(overlay);
    }

    figure.append(frame);
  } else {
    figure.innerHTML = card.svg;
    const svg = figure.firstElementChild;
    if (svg && svg.tagName.toLowerCase() === 'svg') {
      svg.removeAttribute('width');
      svg.removeAttribute('height');
      svg.setAttribute('preserveAspectRatio', 'xMidYMid meet');
    }
  }

  const caption = document.createElement('figcaption');
  caption.textContent = card.label;
  figure.append(caption);
  return figure;
}

/**
 * Replace the preview grid with one card per book page.
 *
 * @param {HTMLElement} previewEl
 * @param {HTMLElement} bookTitle
 * @param {object} book
 */
function renderPreviews(previewEl, bookTitle, book) {
  for (const node of previewEl.querySelectorAll('[data-role="page-preview"]')) {
    node.remove();
  }

  bookTitle.textContent = book.title;

  for (const card of [book.cover, ...book.pages]) {
    previewEl.append(renderCard(card));
  }
}

/**
 * Hand the generated bytes to the browser as a file download.
 *
 * @param {object} book
 */
function downloadBook(book) {
  const blob = new Blob([book.pdfBytes], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = book.filename;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}

function init() {
  const themeInput = document.getElementById('theme-input');
  const nameInput = document.getElementById('name-input');
  const apiKeyInput = document.querySelector('[data-role="api-key"]');
  const generateBtn = document.getElementById('generate-btn');
  const statusEl = document.getElementById('status');
  const errorEl = document.getElementById('error');
  const previewEl = document.getElementById('preview');
  const downloadBtn = document.getElementById('download-btn');
  const bookTitle = document.getElementById('book-title');
  const costNote = document.querySelector('[data-role="cost-note"]');
  const themeNote = document.querySelector('[data-role="theme-note"]');
  const partialActions = document.querySelector('[data-role="partial-actions"]');
  const partialNote = document.querySelector('[data-role="partial-note"]');
  const retryBtn = document.querySelector('[data-role="retry-btn"]');
  const vectorBtn = document.querySelector('[data-role="vector-btn"]');

  const form = themeInput.form;
  if (!form) {
    return;
  }

  // A partial image book is held here so a retry can finish it without
  // re-billing the pictures that already succeeded. It is discarded the moment
  // the theme, the name or the key changes, because it belongs to one book.
  let partial = null;
  // A second submit while the first is in flight would launch a second paid
  // batch. The disabled button covers the common case; this covers the rest.
  let inFlight = false;

  const applyUiState = (phase) => {
    const ui = submitUiState(phase);
    downloadBtn.disabled = ui.downloadDisabled;
    generateBtn.disabled = ui.generateDisabled;
    generateBtn.setAttribute('aria-busy', ui.ariaBusy);
  };

  const clearPartial = () => {
    partial = null;
    partialActions.hidden = true;
    partialNote.textContent = '';
  };

  const showBook = (book) => {
    renderPreviews(previewEl, bookTitle, book);
    statusEl.textContent = readyStatusText(book);
    downloadBtn.onclick = () => downloadBook(book);
    applyUiState('ready');
  };

  const showPartial = (result) => {
    partial = result;
    // A book from a previous run must not stay downloadable under a failed
    // state, or the user downloads the wrong thing.
    downloadBtn.disabled = true;
    downloadBtn.onclick = null;
    statusEl.textContent = '';
    errorEl.textContent = '';
    partialNote.textContent = partialFailureText(result);
    partialActions.hidden = false;
    applyUiState('error');
  };

  const updateCostNote = () => {
    costNote.textContent = costNoteText(hasApiKey(apiKeyInput.value));
  };

  const setThemeNote = (note) => {
    themeNote.textContent = note;
    themeNote.hidden = note.length === 0;
  };

  updateCostNote();
  apiKeyInput.addEventListener('input', () => {
    updateCostNote();
    clearPartial();
  });
  for (const input of [themeInput, nameInput]) {
    input.addEventListener('input', () => {
      // The note describes the theme that was last generated, so it is stale
      // the moment either field changes.
      setThemeNote('');
      clearPartial();
    });
  }

  const run = async (resume) => {
    if (inFlight) {
      return;
    }
    inFlight = true;

    const apiKey = apiKeyInput.value.trim();
    updateCostNote();
    errorEl.textContent = '';
    clearPartial();
    applyUiState('busy');

    try {
      let book;
      if (apiKey) {
        statusEl.textContent = drawingStatusText();
        book = await generateImageBook({
          theme: themeInput.value,
          name: nameInput.value,
          apiKey,
          resume,
        });
      } else {
        book = generateBook(themeInput.value, nameInput.value);
      }

      if (book.complete === false) {
        showPartial(book);
        return;
      }

      showBook(book);
      setThemeNote(themeNoteText(book.matched, book.theme));
    } catch (error) {
      errorEl.textContent = error.message;
      statusEl.textContent = '';
      applyUiState('error');
    } finally {
      inFlight = false;
    }
  };

  form.addEventListener('submit', (event) => {
    event.preventDefault();
    run(null);
  });

  retryBtn.addEventListener('click', () => {
    if (partial) {
      run(partial);
    }
  });

  vectorBtn.addEventListener('click', () => {
    // The user chose the free path. The paid images are abandoned by their own
    // choice, which is the one case where discarding them is not a defect.
    clearPartial();
    errorEl.textContent = '';
    try {
      showBook(generateBook(themeInput.value, nameInput.value));
    } catch (error) {
      errorEl.textContent = error.message;
      statusEl.textContent = '';
      applyUiState('error');
    }
  });
}

if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
}
